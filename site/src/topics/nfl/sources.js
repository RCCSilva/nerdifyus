/** ref: [sourceId, locator?, pdfPage?] → { label, href } */
export function resolveRef([id, at, page]) {
  const s = SOURCES[id];
  return {
    label: [s.short, at, page && `p.${page}`].filter(Boolean).join(' · '),
    href: page && s.page ? s.url + s.page(page) : s.url,
    title: s.title,
  };
}
